package me.kall.narutoui.mui.color;

import org.jetbrains.annotations.NotNull;
import org.jetbrains.annotations.Nullable;

import java.util.Arrays;
import java.util.Locale;
import java.util.Objects;

/**
 * A named color scheme shared by configuration screens and overlays.
 * <p>
 * A scheme carries three related pieces:
 * <ul>
 *     <li>{@link #theme()} for Modern UI configuration screens,</li>
 *     <li>{@link #hud()} for HUD/overlay consumers,</li>
 *     <li>a nine-stop {@link #shimmerRamp()} in the scheme's own color family.</li>
 * </ul>
 * A scheme is usually created from one brand color; the remaining tokens are generated by
 * {@link MuiSchemeGenerator}. Consumers can also pass explicit tokens when they already have a
 * complete palette. The id is stable and is what consumers store in their config. New schemes
 * registered in {@link MuiColorSchemes} automatically appear in every consumer that iterates the
 * catalog.
 */
public final class MuiColorScheme {
    private final String id;
    private final String nameKey;
    private final MuiThemePalette theme;
    private final MuiHudPalette hud;
    private final int[] ramp;

    private MuiColorScheme(@NotNull String id, @NotNull String nameKey, @NotNull MuiThemePalette theme,
                           @NotNull MuiHudPalette hud, int @NotNull [] ramp) {
        this.id = id.toUpperCase(Locale.ROOT);
        this.nameKey = nameKey;
        this.theme = theme;
        this.hud = hud;
        this.ramp = ramp.clone();
    }

    /**
     * Builds a scheme from one brand color using the default presets.
     *
     * @param id      stable id, for example {@code JADE}
     * @param nameKey translation key for the display name
     * @param brand   brand color
     * @return the scheme
     */
    public static @NotNull MuiColorScheme of(@NotNull String id, @NotNull String nameKey, int brand) {
        return of(id, nameKey, brand, MuiSurfaceTint.NEUTRAL_COOL, MuiHudPreset.DERIVED, MuiRampStyle.VALUE_GRADIENT);
    }

    /**
     * Builds a scheme from one brand color.
     *
     * @param id      stable id, for example {@code JADE}
     * @param nameKey translation key for the display name
     * @param brand   brand color
     * @param tint    where the neutral ladder takes its hue from
     * @param hud     how the overlay tokens are produced
     * @param ramp    how the shimmer ramp is produced
     * @return the scheme
     */
    public static @NotNull MuiColorScheme of(@NotNull String id, @NotNull String nameKey, int brand,
                                             @NotNull MuiSurfaceTint tint, @NotNull MuiHudPreset hud,
                                             @NotNull MuiRampStyle ramp) {
        return of(id, nameKey, brand, tint, hud, ramp,
                MuiRampAnchor.nearest(MuiOklch.fromArgb(MuiColorMath.opaque(brand)).hue()));
    }

    /**
     * Builds a scheme from one brand color, with an explicit ramp anchor.
     *
     * @param id      stable id, for example {@code JADE}
     * @param nameKey translation key for the display name
     * @param brand   brand color
     * @param tint    where the neutral ladder takes its hue from
     * @param hud     how the overlay tokens are produced
     * @param ramp    how the shimmer ramp is produced
     * @param anchor  the hue a {@link MuiRampStyle#HUE_SWEEP} ramp travels toward
     * @return the scheme
     */
    public static @NotNull MuiColorScheme of(@NotNull String id, @NotNull String nameKey, int brand,
                                             @NotNull MuiSurfaceTint tint, @NotNull MuiHudPreset hud,
                                             @NotNull MuiRampStyle ramp, @NotNull MuiRampAnchor anchor) {
        return of(id, nameKey, brand, tint, hud, ramp, null, anchor);
    }

    /**
     * Builds a scheme from one brand color whose shimmer spans two hue anchors.
     * <p>
     * A span is how a ramp reads as a journey instead of a fade: the light end is a pale tint of the
     * highlight hue, the deep end a saturated version of the deep hue, and the brand color sits
     * somewhere between them.
     *
     * @param id        stable id, for example {@code AZURE}
     * @param nameKey   translation key for the display name
     * @param brand     brand color
     * @param tint      where the neutral ladder takes its hue from
     * @param hud       how the overlay tokens are produced
     * @param ramp      how the shimmer ramp is produced
     * @param highlight the light end of a {@link MuiRampStyle#HUE_SWEEP} span, or {@code null} to
     *                  start at the accent hue
     * @param deep      the deep end of a {@link MuiRampStyle#HUE_SWEEP} span
     * @return the scheme
     */
    public static @NotNull MuiColorScheme of(@NotNull String id, @NotNull String nameKey, int brand,
                                             @NotNull MuiSurfaceTint tint, @NotNull MuiHudPreset hud,
                                             @NotNull MuiRampStyle ramp, @Nullable MuiRampAnchor highlight,
                                             @NotNull MuiRampAnchor deep) {
        return of(id, nameKey, brand, tint, hud, ramp, highlight, deep, 0);
    }

    /**
     * Builds a scheme from one brand color over a caller-chosen surface.
     * <p>
     * Use this when the player picks the surface themselves: the rest of the ladder and every
     * contrast floor is derived from that surface.
     *
     * @param id        stable id, for example {@code CUSTOM}
     * @param nameKey   translation key for the display name
     * @param brand     brand color
     * @param tint      where the neutral ladder takes its hue from
     * @param hud       how the overlay tokens are produced
     * @param ramp      how the shimmer ramp is produced
     * @param highlight the light end of a {@link MuiRampStyle#HUE_SWEEP} span, or {@code null}
     * @param deep      the deep end of a {@link MuiRampStyle#HUE_SWEEP} span
     * @param surface   surface color, or {@code 0} to derive one from the brand
     * @return the scheme
     */
    public static @NotNull MuiColorScheme of(@NotNull String id, @NotNull String nameKey, int brand,
                                             @NotNull MuiSurfaceTint tint, @NotNull MuiHudPreset hud,
                                             @NotNull MuiRampStyle ramp, @Nullable MuiRampAnchor highlight,
                                             @NotNull MuiRampAnchor deep, int surface) {
        MuiThemePalette tokens = MuiSchemeGenerator.tokens(brand, tint, surface);
        MuiHudPalette overlay = MuiSchemeGenerator.hud(tokens, hud);
        return new MuiColorScheme(id, nameKey, tokens, overlay,
                MuiSchemeGenerator.ramp(tokens, overlay, ramp, highlight, deep));
    }

    /**
     * Builds a scheme from explicit tokens.
     *
     * @param id      stable id
     * @param nameKey translation key for the display name
     * @param theme   UI tokens
     * @param hud     overlay tokens
     * @param ramp    nine ARGB shimmer stops
     * @return the scheme
     */
    public static @NotNull MuiColorScheme of(@NotNull String id, @NotNull String nameKey,
                                             @NotNull MuiThemePalette theme, @NotNull MuiHudPalette hud,
                                             int @NotNull [] ramp) {
        return new MuiColorScheme(id, nameKey, theme, hud, ramp);
    }

    /**
     * Returns the stable id.
     *
     * @return the stable id, upper-cased
     */
    public @NotNull String id() {
        return this.id;
    }

    /**
     * Returns the translation key of the display name.
     *
     * @return the translation key for the display name
     */
    public @NotNull String nameKey() {
        return this.nameKey;
    }

    /**
     * Returns the UI tokens.
     *
     * @return the UI tokens
     */
    public @NotNull MuiThemePalette theme() {
        return this.theme;
    }

    /**
     * Returns the overlay tokens.
     *
     * @return the overlay tokens
     */
    public @NotNull MuiHudPalette hud() {
        return this.hud;
    }

    /**
     * Returns a copy of the shimmer ramp.
     *
     * @return a copy of the nine ARGB shimmer stops
     */
    public int @NotNull [] shimmerRamp() {
        return this.ramp.clone();
    }

    /**
     * Returns the accent color, falling back to the primary color.
     *
     * @return the accent color used by the scheme's shimmer and HUD accent strip
     */
    public int accent() {
        return this.hud.hasAccent() ? this.hud.accent() : this.theme.primary();
    }

    @Override
    public boolean equals(Object other) {
        if (this == other) {
            return true;
        }
        if (!(other instanceof MuiColorScheme scheme)) {
            return false;
        }
        return this.id.equals(scheme.id)
                && this.nameKey.equals(scheme.nameKey)
                && this.theme.equals(scheme.theme)
                && this.hud.equals(scheme.hud)
                && Arrays.equals(this.ramp, scheme.ramp);
    }

    @Override
    public int hashCode() {
        return Objects.hash(this.id, this.nameKey, this.theme, this.hud) * 31 + Arrays.hashCode(this.ramp);
    }

    @Override
    public String toString() {
        return "MuiColorScheme[" + this.id + "]";
    }
}
