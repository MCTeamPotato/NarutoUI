package me.kall.narutoui.mui.color;

import org.jetbrains.annotations.NotNull;
import org.jetbrains.annotations.Nullable;

import java.util.List;
import java.util.concurrent.CopyOnWriteArrayList;

/**
 * Registry of named color schemes.
 * <p>
 * Consumers iterate {@link #all()} instead of maintaining their own enum, so a scheme registered
 * here (by NarutoUI or another mod) becomes available in every settings screen that uses the
 * catalog. Ids are stable config values; display names come from {@link MuiColorScheme#nameKey()}.
 * <p>
 * The built-ins are declared as one brand color plus three presets each. The 27 colors a scheme
 * used to spell out are generated by {@link MuiSchemeGenerator} at class-init time and cached on
 * the scheme.
 */
public final class MuiColorSchemes {
    private static final List<MuiColorScheme> SCHEMES = new CopyOnWriteArrayList<>();

    /** Warm gold on a cool near-black surface, with the original warm overlay palette. */
    public static final MuiColorScheme NARUTO = MuiColorScheme.of(
            "NARUTO", "narutoui.scheme.naruto", 0xFFE0A64A,
            MuiSurfaceTint.NEUTRAL_COOL, MuiHudPreset.CHAKRA, MuiRampStyle.SEMANTIC_HEAT,
            MuiRampAnchor.RED);

    /** White and gray, without an accent. */
    public static final MuiColorScheme CLASSIC = MuiColorScheme.of(
            "CLASSIC", "narutoui.scheme.classic", 0xFFFFFFFF,
            MuiSurfaceTint.NEUTRAL_COOL, MuiHudPreset.NEUTRAL, MuiRampStyle.NEUTRAL,
            MuiRampAnchor.RED);

    /** Jade accent on a deep green surface; the wave runs pale water through jade to deep green. */
    public static final MuiColorScheme JADE = MuiColorScheme.of(
            "JADE", "narutoui.scheme.jade", 0xFF3DDC97,
            MuiSurfaceTint.BRAND, MuiHudPreset.DERIVED, MuiRampStyle.HUE_SWEEP,
            MuiRampAnchor.CYAN, MuiRampAnchor.GREEN);

    /** Azure accent on a deep blue surface; the wave runs pale cyan to deep blue. */
    public static final MuiColorScheme AZURE = MuiColorScheme.of(
            "AZURE", "narutoui.scheme.azure", 0xFF5AA9FF,
            MuiSurfaceTint.BRAND, MuiHudPreset.DERIVED, MuiRampStyle.HUE_SWEEP,
            MuiRampAnchor.STEEL, MuiRampAnchor.BLUE);

    /** Sakura accent on a warm charcoal surface; the wave runs pale rose to blood red. */
    public static final MuiColorScheme SAKURA = MuiColorScheme.of(
            "SAKURA", "narutoui.scheme.sakura", 0xFFFF8FB3,
            MuiSurfaceTint.BRAND, MuiHudPreset.DERIVED, MuiRampStyle.HUE_SWEEP,
            MuiRampAnchor.ROSE, MuiRampAnchor.RED);

    /** Neutral graphite surface with a light accent; the wave runs gray to steel teal. */
    public static final MuiColorScheme GRAPHITE = MuiColorScheme.of(
            "GRAPHITE", "narutoui.scheme.graphite", 0xFFD6D9E0,
            MuiSurfaceTint.NEUTRAL_COOL, MuiHudPreset.DERIVED, MuiRampStyle.HUE_SWEEP,
            MuiRampAnchor.CYAN);

    static {
        register(NARUTO);
        register(CLASSIC);
        register(JADE);
        register(AZURE);
        register(SAKURA);
        register(GRAPHITE);
    }

    private MuiColorSchemes() {}

    /**
     * Registers or replaces a scheme. The id is the key consumers store in their configs.
     *
     * @param scheme the scheme
     * @return the registered scheme
     */
    public static @NotNull MuiColorScheme register(@NotNull MuiColorScheme scheme) {
        SCHEMES.removeIf(existing -> existing.id().equalsIgnoreCase(scheme.id()));
        SCHEMES.add(scheme);
        return scheme;
    }

    /**
     * Returns the schemes in registration order.
     *
     * @return an immutable snapshot
     */
    public static @NotNull List<MuiColorScheme> all() {
        return List.copyOf(SCHEMES);
    }

    /**
     * Looks up a scheme by id, ignoring case.
     *
     * @param id the id, or {@code null}
     * @return the scheme, or {@code null}
     */
    public static @Nullable MuiColorScheme byId(@Nullable String id) {
        if (id == null || id.isBlank()) {
            return null;
        }
        for (MuiColorScheme scheme : SCHEMES) {
            if (scheme.id().equalsIgnoreCase(id)) {
                return scheme;
            }
        }
        return null;
    }
}
